"""Benchmark all navigation methods on a synthetic, obstacle-near slalom route.

The path is derived from the recorded Freiburg route, then laterally perturbed
into alternating turns. Candidate paths must remain collision-clear and pass
near recorded obstacles. A seeded set of start offsets is shared across
methods so each method receives the same 25 scenarios (100 attempts total).

Run from the repository root:
    python src/complex_path_benchmark.py --runs 100

Outputs are written to results/complex_path/: route metadata, per-attempt CSV,
and a JSON summary. No benchmark results are pre-generated by this script.
"""

from __future__ import annotations

import argparse
import csv
import json
import math
import sys
import time
from pathlib import Path

import numpy as np
import pybullet as bullet

from recorded_demo import (
    MARGIN,
    METHODS,
    RecordedMap,
    astar_path,
    direct_path,
    dmp_path,
    learn_dmp,
    read_log,
    resample,
    simulate,
)

ROOT = Path(__file__).resolve().parents[1]


def route_turn_count(route: np.ndarray, threshold_deg: float = 25.0) -> int:
    vectors = np.diff(route, axis=0)
    headings = np.unwrap(np.arctan2(vectors[:, 1], vectors[:, 0]))
    changes = np.diff(headings)
    return int(np.count_nonzero(np.abs(np.degrees(changes)) >= threshold_deg))


def construct_complex_route(world: RecordedMap):
    """Find a safe alternating-offset route with several meaningful turns."""
    base = world.reference
    distances = np.r_[0.0, np.cumsum(np.linalg.norm(np.diff(base, axis=0), axis=1))]
    total = float(distances[-1])
    if total < 12:
        raise ValueError("The selected recorded route is too short to create the slalom benchmark.")

    # Try progressively tighter, stronger slaloms. Each candidate is checked
    # against the same inflated rover-footprint clearance screen as the planners.
    candidates = [(spacing, amplitude, phase)
                  for spacing in (3.0, 2.5, 2.0)
                  for amplitude in (0.45, 0.65, 0.85, 1.05, 1.25)
                  for phase in (0, 1)]
    best = None
    for spacing, amplitude, phase in candidates:
        anchors_s = np.r_[np.arange(0.0, total, spacing), total]
        anchors = np.column_stack((np.interp(anchors_s, distances, base[:, 0]),
                                   np.interp(anchors_s, distances, base[:, 1])))
        offset = np.zeros(len(anchors_s))
        for i in range(1, len(offset) - 1):
            offset[i] = amplitude * (-1.0 if (i + phase) % 2 else 1.0)
        tangents = np.gradient(anchors, axis=0)
        norms = np.linalg.norm(tangents, axis=1)
        if np.any(norms < 1e-8):
            continue
        normals = np.column_stack((-tangents[:, 1], tangents[:, 0])) / norms[:, None]
        perturbed = anchors + offset[:, None] * normals
        candidate = resample(perturbed, 0.08)
        clearances = np.array([world.clearance(p) for p in candidate])
        minimum = float(clearances.min())
        turns = route_turn_count(candidate)
        # Prefer routes that are safe, turn-rich, and demonstrably close to map
        # obstacles. Do not silently downgrade to the original easy route.
        if minimum >= MARGIN and minimum <= 0.95 and turns >= 6:
            score = turns - abs(minimum - 0.55)
            if best is None or score > best[0]:
                best = (score, candidate, minimum, turns, spacing, amplitude, phase)
    if best is None:
        raise RuntimeError(
            "Could not construct a safe, obstacle-near slalom route from this map. "
            "Try another route window or adjust the candidate spacing/amplitudes."
        )
    _, route, minimum, turns, spacing, amplitude, phase = best
    world.reference = route
    return {
        "construction": "alternating lateral offsets from recorded route, screened against recorded obstacle map",
        "source_route_scan_indices": [300, 549],
        "route_length_m": round(float(np.linalg.norm(np.diff(route, axis=0), axis=1).sum()), 2),
        "route_points": int(len(route)),
        "turns_over_25_deg": turns,
        "minimum_grid_clearance_m": round(minimum, 3),
        "offset_spacing_m": spacing,
        "lateral_amplitude_m": amplitude,
        "alternation_phase": phase,
    }


def make_trials(world: RecordedMap, runs: int, seed: int):
    """Build paired starts: each method receives the same pose for each case."""
    rng = np.random.default_rng(seed)
    heading = math.atan2(world.reference[1, 1] - world.reference[0, 1],
                         world.reference[1, 0] - world.reference[0, 0])
    normal = np.array((-math.sin(heading), math.cos(heading)))
    starts = []
    for i in range(runs):
        # Symmetric, reproducible offsets and heading errors; larger offsets are
        # intentionally included to exercise path reconnection and rejection.
        offset = float(rng.choice(np.array([-1.5, -1.0, -0.5, 0.0, 0.5, 1.0, 1.5])))
        heading_error = float(rng.choice(np.array([-50, -35, -20, 0, 20, 35, 50])))
        jitter = rng.normal(0.0, 0.08, size=2)
        xy = world.reference[0] + offset * normal + jitter
        starts.append((float(xy[0]), float(xy[1]), heading + math.radians(heading_error), offset, heading_error, i))
    return starts


def run(runs: int = 100, seed: int = 20261104):
    if runs < len(METHODS) or runs % len(METHODS) != 0:
        raise ValueError(f"--runs must be a positive multiple of {len(METHODS)} for balanced method comparisons.")
    poses, points = read_log()
    world = RecordedMap(poses, points)
    route_info = construct_complex_route(world)
    model = learn_dmp(world.reference)
    starts = make_trials(world, runs // len(METHODS), seed)
    out = ROOT / "results" / "complex_path"
    out.mkdir(parents=True, exist_ok=True)

    np.savetxt(out / "route.csv", world.reference, delimiter=",", header="x_m,y_m", comments="")
    rows = []
    bullet.connect(bullet.DIRECT)
    try:
        for start in starts:
            for method in METHODS:
                t0 = time.perf_counter()
                if method == "Direct waypoints":
                    path = direct_path(world, start)
                elif method == "Local A*":
                    path = astar_path(world, start)
                else:
                    path = dmp_path(world, start, model, method == "Obstacle-aware DMP")
                planning_ms = (time.perf_counter() - t0) * 1000
                if not world.clear_path(path):
                    status, trace, minimum, duration = "rejected", np.array([start[:2]]), world.clearance(start[:2]), 0.0
                else:
                    status, trace, minimum, duration = simulate(world, path, start)
                rows.append({
                    "case_id": start[5], "method": method, "start_offset_m": start[3],
                    "heading_offset_deg": start[4], "status": status,
                    "minimum_clearance_m": round(float(minimum), 3),
                    "goal_error_m": round(float(np.linalg.norm(trace[-1] - world.reference[-1])), 3),
                    "planning_ms": round(float(planning_ms), 2), "duration_s": round(float(duration), 2),
                    "distance_m": round(float(np.linalg.norm(np.diff(trace, axis=0), axis=1).sum()), 2),
                })
                print(f"case={start[5]:03d} {method:20} {status}", flush=True)
    finally:
        bullet.disconnect()

    with (out / "trials.csv").open("w", newline="") as file:
        writer = csv.DictWriter(file, fieldnames=list(rows[0]))
        writer.writeheader()
        writer.writerows(rows)

    summary = {
        "dataset": "Freiburg Campus 2004-07-14 raw CARMEN log",
        "simulator": "PyBullet DIRECT; Husky URDF; 120 Hz",
        "seed": seed,
        "requested_total_attempts": runs,
        "cases_per_method": len(starts),
        "methods": {},
        "route": route_info,
        "notes": "Rejected plans are counted separately from simulated drives; results are simulation outcomes, not field trials.",
    }
    for method in METHODS:
        subset = [row for row in rows if row["method"] == method]
        completed = [row for row in subset if row["status"] == "completed"]
        summary["methods"][method] = {
            "attempts": len(subset),
            "completed": len(completed),
            "rejected": sum(row["status"] == "rejected" for row in subset),
            "collisions": sum(row["status"] == "collision" for row in subset),
            "safety_stops": sum(row["status"] == "safety_stop" for row in subset),
            "timeouts": sum(row["status"] == "timeout" for row in subset),
            "completion_rate_pct": round(100 * len(completed) / len(subset), 1),
            "median_goal_error_m": round(float(np.median([row["goal_error_m"] for row in completed])), 3) if completed else None,
            "median_planning_ms": round(float(np.median([row["planning_ms"] for row in subset])), 2),
        }
    (out / "summary.json").write_text(json.dumps(summary, indent=2) + "\n")
    print(json.dumps(summary, indent=2))


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description="Run 100 paired trials on an obstacle-near slalom route.")
    parser.add_argument("--runs", type=int, default=100, help="Total attempts across all methods; balanced, default 100.")
    parser.add_argument("--seed", type=int, default=20261104)
    args = parser.parse_args()
    run(args.runs, args.seed)
